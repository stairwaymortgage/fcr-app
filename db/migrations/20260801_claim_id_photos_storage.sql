-- ==========================================================
-- STORAGE LOCKDOWN: id-photos (GOVERNMENT ID PHOTOS)
-- Created 2026-08-01. APPLIED — verified 2026-08-03: the id-photos bucket exists
-- with public = false, and all three policies below are present on
-- storage.objects. Re-running is safe; the bucket INSERT re-asserts public =
-- false on conflict, which is the point of writing it that way.
-- ==========================================================
--
-- This bucket holds photographs of driving licences and passports belonging to
-- named people whose addresses are already public in the DBPR registry. It is
-- the single most sensitive store in the project. A leak here is an identity
-- theft kit, not an embarrassment.
--
-- Four independent things must all hold for a photo to stay private:
--
--   1. the bucket is private, so there is no public URL to guess
--   2. RLS on storage.objects restricts every path to its owning user
--   3. reads happen through short-lived signed URLs, minted server-side
--   4. the row in public.claims stores a PATH, never a URL
--
-- Any one of them failing is survivable. That is the point of having four.
-- ==========================================================


-- ==========================================================
-- 1. THE BUCKET
-- ==========================================================
--
-- public = false is the whole ballgame. In a public bucket every object is
-- readable at a guessable URL by anyone on the internet, RLS is not consulted
-- at all, and no amount of correct policy below would matter.
--
-- file_size_limit 10 MB: a modern phone camera produces 3-8 MB for a document
-- photo, and HEIC from an iPhone can exceed 8. Set lower and real contractors
-- silently fail at the one step we need them to complete.
--
-- allowed_mime_types deliberately EXCLUDES image/svg+xml. SVG is a script
-- carrier, not a photograph — nobody photographs an ID into an SVG, and if one
-- is ever rendered inline it executes. There is no upside to allowing it.
--
-- ⚠ allowed_mime_types is checked against the Content-Type the CLIENT sends.
-- It is a guardrail against mistakes, NOT a proof of file contents. Treat every
-- object here as untrusted bytes: never render one inline, never pass one to an
-- image processor that parses metadata, always serve as an attachment.
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'id-photos',
  'id-photos',
  false,
  10485760,  -- 10 MB
  ARRAY['image/jpeg', 'image/png', 'image/webp', 'image/heic', 'image/heif']
)
ON CONFLICT (id) DO UPDATE
  SET public             = false,   -- re-assert on every run: this must never drift
      file_size_limit    = EXCLUDED.file_size_limit,
      allowed_mime_types = EXCLUDED.allowed_mime_types;


-- ==========================================================
-- 2. PATH STRUCTURE  →  {claimant_user_id}/{claim_id}.{ext}
-- ==========================================================
--
-- The first segment is the user's auth.uid(). That is what every policy below
-- tests, so the path is not a naming convention — it IS the access control.
--
-- claim_id is generated by the application BEFORE the upload (a client-side
-- uuid), then used as the primary key of the claims row. Generating it up front
-- is what lets the file and the row share an identifier without a round trip.
--
-- A fresh uuid PER ATTEMPT, not per claim: policies below forbid overwriting,
-- so a retry after a half-failed upload must not reuse the old id or it will
-- collide and fail forever.


-- ==========================================================
-- 3. RLS ON storage.objects
-- ==========================================================
--
-- Supabase enables RLS on storage.objects by default; asserted here because
-- every policy below is worthless without it.
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;

-- ---------- anon: NOTHING ----------
-- There is deliberately no policy granting anon anything on this bucket.
-- Under RLS, absence of a policy is a denial — so this is enforced, not merely
-- unmentioned. Do not add one "for the upload page"; uploads are authenticated.

-- ---------- contractor: INSERT into own folder only ----------
CREATE POLICY "claimant uploads own id photo"
  ON storage.objects FOR INSERT
  TO authenticated
  WITH CHECK (
    bucket_id = 'id-photos'
    -- First path segment must be the caller's own uid. This is the isolation.
    AND (storage.foldername(name))[1] = auth.uid()::text
    -- Exactly one folder level: forbids "me/../someone-else" style nesting and
    -- keeps the path shape the review query below depends on.
    AND array_length(storage.foldername(name), 1) = 1
  );

-- ---------- contractor: SELECT own folder only ----------
CREATE POLICY "claimant reads own id photo"
  ON storage.objects FOR SELECT
  TO authenticated
  USING (
    bucket_id = 'id-photos'
    AND (storage.foldername(name))[1] = auth.uid()::text
  );

-- ---------- NO UPDATE, NO DELETE for contractors. INTENTIONAL. ----------
--
-- Not an oversight, and not tidiness. An ID photo is evidence in a manual
-- review. If the claimant could UPDATE the object they could let Jim approve a
-- genuine licence and then swap the bytes afterwards, leaving an approved claim
-- backed by a file nobody ever reviewed — with no trace, because the path and
-- the row are unchanged.
--
-- DELETE is withheld for the same reason: an approved claim whose evidence has
-- been erased by the person it approved cannot be audited later.
--
-- The cost is that a contractor cannot retract a photo themselves. That is a
-- support request, and it is the correct trade for a verification record.

-- ---------- admin: full access ----------
CREATE POLICY "admin full access id photos"
  ON storage.objects FOR ALL
  TO authenticated
  USING (bucket_id = 'id-photos' AND is_admin())
  WITH CHECK (bucket_id = 'id-photos' AND is_admin());
-- is_admin() reads app_metadata ONLY. See 20260801_fix_is_admin.sql — when it
-- also trusted user_metadata, any signed-up visitor could have satisfied this.


-- ==========================================================
-- 4. THE claims.id_photo_url COLUMN IS A PATH, NOT A URL
-- ==========================================================
--
-- The column is named id_photo_url and that name is a trap: it invites storing
-- a public URL, and a public URL to this bucket is the one thing that undoes
-- everything above. Store the storage path — 'a1b2.../c3d4....jpg' — and mint a
-- signed URL at the moment of viewing.
--
-- Renaming the column is the honest fix; left for a migration that can update
-- the application in the same change.
COMMENT ON COLUMN public.claims.id_photo_url IS
  'STORAGE PATH inside the private id-photos bucket ({user_id}/{claim_id}.ext) - NOT a URL. Never store a public URL here; the bucket is private and reads go through short-lived signed URLs.';


