-- To see the photo: Storage → id-photos → open the folder named for the
-- claimant's user id → click the file. The dashboard authenticates as the
-- service role, so this works without an admin UI and without making anything
-- public.
--
-- To approve:
--   UPDATE claims SET status='approved', reviewed_at=now(),
--          reviewed_by_user_id='<jim-uid>'
--    WHERE id='<claim-id>';
--   UPDATE contractors SET claimed_by_user_id='<claimant-uid>'
--    WHERE dbpr_sync_key='<key>';
--
-- To reject:
--   UPDATE claims SET status='rejected', reviewed_at=now(),
--          reviewed_by_user_id='<jim-uid>', rejection_reason='<why>'
--    WHERE id='<claim-id>';
--
-- ⚠ The two approve statements must both run. A claims row marked approved
-- while contractors.claimed_by_user_id is still null is an approval that grants
-- nothing — the contractor signs in, sees no profile, and reports a bug that
-- looks like auth. Worth a trigger once the admin UI exists.


